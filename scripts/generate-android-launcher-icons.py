"""Generate the Android launcher icons from the web icon. Same input, same output: rerun after changing the art."""
import shutil
from pathlib import Path

from PIL import Image, ImageChops, ImageDraw

root = Path(__file__).resolve().parent.parent
source = root / "apps/web/public/icons/grogoni-icon-512.png"
res = root / "apps/android/app/src/main/res"
density = {"mdpi": 1, "hdpi": 1.5, "xhdpi": 2, "xxhdpi": 3, "xxxhdpi": 4}
ART_DP = 66  # Android keeps a 66dp circle of the 108dp adaptive layer visible on every mask shape.

art = Image.open(source).convert("RGB")
art = art.crop(ImageChops.difference(art, Image.new("RGB", art.size, "white")).getbbox())


def placed(canvas: int, box: int) -> Image.Image:
    """Centre the art, scaled to fit a box, on a white canvas."""
    scale = box / max(art.size)
    fitted = art.resize((round(art.width * scale), round(art.height * scale)), Image.LANCZOS)
    image = Image.new("RGB", (canvas, canvas), "white")
    image.paste(fitted, ((canvas - fitted.width) // 2, (canvas - fitted.height) // 2))
    return image


for name, factor in density.items():
    folder = res / f"mipmap-{name}"
    folder.mkdir(parents=True, exist_ok=True)
    legacy = round(48 * factor)
    # The art must stay inside the round mask, whose inscribed square is 70% of the width.
    square = placed(legacy, round(legacy * 0.7))
    square.save(folder / "ic_launcher.png", optimize=True)
    mask = Image.new("L", (legacy * 4, legacy * 4), 0)
    ImageDraw.Draw(mask).ellipse((0, 0, legacy * 4 - 1, legacy * 4 - 1), fill=255)
    rounded = square.convert("RGBA")
    rounded.putalpha(mask.resize((legacy, legacy), Image.LANCZOS))
    rounded.save(folder / "ic_launcher_round.png", optimize=True)
    placed(round(108 * factor), round(ART_DP * factor * 0.86)).save(folder / "ic_launcher_foreground.png", optimize=True)

# Play's listing icon is a 512 x 512 32-bit PNG, uploaded in Console.
listing = root / "apps/android/play-listing"
listing.mkdir(exist_ok=True)
placed(512, 410).convert("RGBA").save(listing / "icon-512.png", optimize=True)

adaptive = res / "mipmap-anydpi-v26"
adaptive.mkdir(exist_ok=True)
layout = """<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-android-launcher-icons.py. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@android:color/white" />
    <foreground android:drawable="@mipmap/ic_launcher_foreground" />
</adaptive-icon>
"""
(adaptive / "ic_launcher.xml").write_text(layout)
shutil.copy(adaptive / "ic_launcher.xml", adaptive / "ic_launcher_round.xml")
