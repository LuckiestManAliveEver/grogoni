// Writes services/api/src/edge-route-inventory.generated.ts from the live route registration.
// `--check` fails (exit 1) when the committed file differs, without writing.
import { readFile, writeFile } from "node:fs/promises";
import prettier from "prettier";
import { fileURLToPath } from "node:url";
import { collectEdgeRouteInventory } from "../services/api/src/edge-route-inventory.js";

const target = fileURLToPath(
  new URL("../services/api/src/edge-route-inventory.generated.ts", import.meta.url)
);

export async function renderEdgeRouteInventory(
  inventory: Awaited<ReturnType<typeof collectEdgeRouteInventory>>
): Promise<string> {
  const rows = inventory.map((entry) => `  ${JSON.stringify(entry)}`).join(",\n");
  // Formatted with the repository's Prettier config so `pnpm format` accepts the file as written.
  const options = (await prettier.resolveConfig(target)) ?? {};
  return prettier.format(
    `// Generated by scripts/generate-edge-route-inventory.ts. Do not edit by hand:
// run \`pnpm generate:edge-routes\` after changing CP2 or MCP routes.
import type { EdgeRouteInventoryEntry } from "./edge-route-inventory.js";

export const edgeRouteInventory: readonly EdgeRouteInventoryEntry[] = [
${rows}
];
`,
    { ...options, filepath: target }
  );
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const rendered = await renderEdgeRouteInventory(await collectEdgeRouteInventory());
  const current = await readFile(target, "utf8").catch(() => "");
  if (process.argv.includes("--check")) {
    if (current !== rendered) {
      console.error(
        "services/api/src/edge-route-inventory.generated.ts is out of date. Run `pnpm generate:edge-routes`."
      );
      process.exit(1);
    }
  } else if (current !== rendered) {
    await writeFile(target, rendered);
    console.log("Wrote services/api/src/edge-route-inventory.generated.ts");
  }
  process.exit(0);
}
