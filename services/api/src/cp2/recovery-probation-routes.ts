export function probationAllows(method: string, url: string): boolean {
  const verb = method === "HEAD" ? "GET" : method;
  const key = `${verb} ${url}`;
  if (verb === "GET" || verb === "OPTIONS") return probationRefusedReads[key] === undefined;
  return probationAllowedWrites.has(key);
}
