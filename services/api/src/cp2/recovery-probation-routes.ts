/**
 * Which routes a session on trusted-device recovery probation may call
 * (docs/authentication/trusted-device-recovery-approval.md).
 *
 * Writes are allowlisted: a probation session may call only a write route named in
 * `probationAllowedWrites`. Anything else, including a route added later and not classified
 * here, is refused, so a new route fails safe. `tests/recovery-probation-routes.test.ts` fails
 * until every registered write route is in exactly one of the two lists, and it checks the
 * runtime guard refuses an unclassified route.
 *
 * Reads are allowed, except the GET routes in `probationRefusedReads` that change sign-in or
 * API access. Static assets change name on every build, and reading is not what probation stops.
 *
 * Generated from the route table by these rules, then reviewed. Refused: every /auth write except
 * the recovery steps below; sessions; account ownership and restoration; staff and roles; shop and
 * account deletion and bulk export; linking outside accounts, messaging channels, providers and
 * credentials; devices that receive messages later (except this browser's own E2EE device and
 * push subscription, which undo removes); public share links and device trust; identity links;
 * API tokens.
 */

