export interface EdgeJobOutcome {
  job: string;
  status: "completed" | "disabled" | "skipped";
  durationMs: number;
  result?: unknown;
  reason?: string;
}

/**
 * One job run's transaction. The implementation must take the per-job lock with a try-lock
 * BEFORE the store lock: an overlapping trigger then sees the job lock held and returns at once,
 * instead of queueing on the store lock behind the run and running again after it commits.
 */
export interface EdgeJobDatabase {
  jobTransaction: <T>(
    input: {
      lockKey: string;
      storeLock: boolean;
      idle?: (client: PoolClient) => Promise<boolean>;
    },
    action: (client: PoolClient) => Promise<T>
  ) => Promise<
    { acquired: true; result: T } | { acquired: true; idle: true } | { acquired: false }
  >;
}

export async function runEdgeJob(
  database: EdgeJobDatabase,
  jobName: string,
  options: {
    storeDependencies?: Partial<Cp2StoreOptions>;
    environment?: NodeJS.ProcessEnv;
    now?: () => Date;
    daemon?: Pick<EdgeDaemon, "runWorker">;
  } = {}
): Promise<EdgeJobOutcome> {
  const definition = edgeJobDefinitions[jobName];
  if (definition === undefined) throw new Error(`Unknown background job ${jobName}.`);
  const environment = options.environment ?? process.env;
  const started = Date.now();
  const outcome = (status: EdgeJobOutcome["status"], extra: Partial<EdgeJobOutcome> = {}) => ({
    job: jobName,
    status,
    durationMs: Date.now() - started,
    ...extra
  });
  if (!definition.enabled(environment)) return outcome("disabled");

  const run = await database.jobTransaction(
    {
      lockKey: `edge:job:${jobName}`,
      storeLock: definition.needsStore,
      ...(definition.idle === undefined ? {} : { idle: definition.idle })
    },
    async (client) => {
      const {
        createPostgresAccountAiAssetStore,
        createPostgresAttachmentBlobStore,
        loadTransactionalCp2Snapshot,
        saveTransactionalCp2Snapshot
      } = await import("./cp2/postgres-store.js");
      const { createCp2Store } = await import("./cp2/store.js");
      const { createPostgresRuntimeApprovalMaintenance } =
        await import("./cp2/domains/agent-runtime/runtime-approval-store.js");
      const { createEdgeFulfillmentService, readFulfillmentRetentionHours } =
        await import("./edge-store-dependencies.js");
      const now = options.now?.() ?? new Date();
      const pool = transactionPool(client);
      const store = createCp2Store({
        ...options.storeDependencies,
        runtimeApprovalStore: createPostgresRuntimeApprovalMaintenance(client),
        workspaceRoot: "/tmp/grogoni-workspace",
        conversationAttachmentBlobStore: createPostgresAttachmentBlobStore(pool),
        accountAiAssetStore: createPostgresAccountAiAssetStore(pool)
      });
      const baseline = definition.needsStore ? await loadTransactionalCp2Snapshot(client) : null;
      if (baseline !== null) store.hydrateSnapshot(structuredClone(baseline));
      const fulfillment = createEdgeFulfillmentService(
        pool,
        store,
        readFulfillmentRetentionHours(environment)
      );
      const result = await definition.run({
        store,
        fulfillment,
        client,
        now,
        environment,
        ...(options.daemon === undefined ? {} : { daemon: options.daemon })
      });
      if (baseline !== null) await saveTransactionalCp2Snapshot(client, store.snapshot(), baseline);
      return result;
    }
  );
  if (!run.acquired) return outcome("skipped", { reason: "already_running" });
  return "idle" in run
    ? outcome("completed", { result: { idle: true } })
    : outcome("completed", { result: run.result });
}
