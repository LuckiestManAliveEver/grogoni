import type { PoolClient } from "pg";
import type { Cp2Store, Cp2StoreOptions } from "./cp2/store.js";
import type { FulfillmentService } from "./cp2/domains/fulfillment/service.js";
import { transactionPool } from "./edge-transaction-pool.js";
import type { EdgeDaemon } from "./daemon/edge-lane.js";

/**
 * Background jobs on the Edge runtime. The Node API runs these as in-process interval runners
 * (services/api/src/index.ts); an Edge isolate has no lifetime to run timers in, so each job runs
 * to completion in one request instead: Supabase Cron calls POST /internal/jobs/:job/run on the
 * schedule generated by edge-job-schedule.ts (pnpm jobs:schedule:supabase), and this module does exactly what the matching
 * runner's tick does, against a store hydrated from Postgres and saved back in the same
 * transaction.
 *
 * Each job's `enabled` flag reads the same ENABLE_* variable as its Node runner, with the same
 * default: every runner is on unless set to "false", except account deletion, which purges data
 * and runs only when ENABLE_ACCOUNT_DELETION_RUNNER is "true".
 */

interface JobContext {
  store: Cp2Store;
  fulfillment: FulfillmentService;
  client: PoolClient;
  now: Date;
  environment: NodeJS.ProcessEnv;
  /** The daemon's server lane; absent where no queue database is wired. */
  daemon?: Pick<EdgeDaemon, "runWorker">;
}

interface EdgeJobDefinition {
  /**
   * How often Supabase Cron triggers it (a cron expression, or pg_cron's "N seconds"); mirrors
   * the Node runner's default interval. The Node *_INTERVAL_MS variables do not apply on Edge:
   * the schedule is the interval.
   */
  schedule: string;
  enabled: (environment: NodeJS.ProcessEnv) => boolean;
  /**
   * False for jobs that only touch their own table: they neither load the domain store nor take
   * the store lock, so they never make a user request wait.
   */
  needsStore: boolean;
  /**
   * Optional cheap check, run after the job lock and before the store lock: true means the run
   * would do nothing, so it returns without loading the store or making requests wait.
   */
  idle?: (client: PoolClient) => Promise<boolean>;
  run: (context: JobContext) => Promise<unknown>;
}

const onUnlessDisabled = (variable: string) => (environment: NodeJS.ProcessEnv) =>
  environment[variable] !== "false";
const positive = (value: string | undefined, fallback: number) => {
  const parsed = Number(value);
  return Number.isSafeInteger(parsed) && parsed > 0 ? parsed : fallback;
};

/** Same rule as connected-mailbox-sync-runner.ts: at least a minute, invalid values rejected. */
function mailboxSyncInterval(environment: NodeJS.ProcessEnv): number {
  const raw = environment.CONNECTED_MAILBOX_SYNC_INTERVAL_MS;
  if (raw === undefined || raw.trim() === "") return 5 * 60_000;
  const value = Number(raw);
  if (!Number.isSafeInteger(value) || value < 60_000)
    throw new Error("Connected mailbox sync interval must be at least 60000 milliseconds.");
  return value;
}

